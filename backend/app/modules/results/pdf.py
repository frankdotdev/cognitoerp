"""
Report card PDF generation (doc 011, doc 015). Renders an HTML template
with the student's actual scores and the SCHOOL'S actual branding (logo,
primary color) — this is the same principle as the frontend's report card
preview screen: a generated document is only worth anything if it looks
like the school's own document, not a generic Cognitio template with the
school's name substituted in.

Template is plain Jinja2 + inline CSS (no external stylesheet — WeasyPrint
renders from a self-contained HTML string, and inlining avoids any
relative-path/asset-resolution complexity for a document generated
server-side with no browser context).
"""
import io

from jinja2 import Template
from weasyprint import HTML

_TEMPLATE = Template("""
<!DOCTYPE html>
<html>
<head>
<meta charset="utf-8">
<style>
  @page { size: A4; margin: 2cm; }
  body { font-family: 'Helvetica', 'Arial', sans-serif; color: #14181F; font-size: 11pt; }
  .header { display: flex; align-items: center; gap: 12px; border-bottom: 3px solid {{ primary_color }}; padding-bottom: 16px; margin-bottom: 20px; }
  .header img { width: 48px; height: 48px; object-fit: contain; }
  .header .title { font-size: 16pt; font-weight: bold; color: {{ primary_color }}; }
  .header .subtitle { font-size: 10pt; color: #5B6472; }
  .meta { display: flex; flex-wrap: wrap; gap: 16px; font-size: 10pt; margin-bottom: 20px; }
  .meta div { min-width: 45%; }
  .meta .label { color: #98A1AD; }
  table { width: 100%; border-collapse: collapse; margin-bottom: 20px; font-size: 10pt; }
  th { text-align: left; border-bottom: 2px solid #14181F; padding: 6px 4px; }
  td { padding: 6px 4px; border-bottom: 1px solid #E5E8EA; }
  .right { text-align: right; }
  .summary { display: flex; justify-content: space-between; font-weight: bold; font-size: 12pt; padding-top: 12px; border-top: 2px solid #E5E8EA; margin-bottom: 20px; }
  .comment { font-size: 10pt; font-style: italic; margin-bottom: 24px; }
  .comment .label { color: #98A1AD; font-style: normal; margin-bottom: 4px; }
  .footer { display: flex; justify-content: space-between; font-size: 9pt; color: #98A1AD; border-top: 1px solid #E5E8EA; padding-top: 12px; }
</style>
</head>
<body>
  <div class="header">
    {% if logo_url %}<img src="{{ logo_url }}" alt="logo">{% endif %}
    <div>
      <div class="title">{{ school_name }}</div>
      <div class="subtitle">Report Card — {{ term }}</div>
    </div>
  </div>

  <div class="meta">
    <div><span class="label">Student:</span> {{ student_name }}</div>
    <div><span class="label">Admission No:</span> {{ admission_number }}</div>
    <div><span class="label">Class:</span> {{ class_name }}</div>
    {% if attendance_percent is not none %}<div><span class="label">Attendance:</span> {{ attendance_percent }}%</div>{% endif %}
  </div>

  <table>
    <thead><tr><th>Subject</th><th class="right">Score</th><th class="right">Grade</th></tr></thead>
    <tbody>
      {% for subject, s in subject_scores.items() %}
      <tr><td>{{ subject }}</td><td class="right">{{ s.total }}</td><td class="right">{{ s.grade }}</td></tr>
      {% endfor %}
    </tbody>
  </table>

  <div class="summary">
    <span>Overall average</span>
    <span>{{ overall_average }}%{% if class_position %} — Position {{ class_position }} in class{% endif %}</span>
  </div>

  {% if teacher_comment %}
  <div class="comment">
    <div class="label">Class teacher's comment</div>
    {{ teacher_comment }}
  </div>
  {% endif %}

  <div class="footer">
    <span>Generated by Cognitio ERP</span>
    <span>{{ generated_date }}</span>
  </div>
</body>
</html>
""")


def render_report_card_pdf(*, school_name: str, logo_url: str | None, primary_color: str, student_name: str,
                            admission_number: str, class_name: str, term: str, subject_scores: dict,
                            overall_average: float, class_position: int | None, attendance_percent: float | None,
                            teacher_comment: str | None, generated_date: str) -> bytes:
    html_content = _TEMPLATE.render(
        school_name=school_name, logo_url=logo_url, primary_color=primary_color or "#0E7C4A",
        student_name=student_name, admission_number=admission_number, class_name=class_name, term=term,
        subject_scores=subject_scores, overall_average=overall_average, class_position=class_position,
        attendance_percent=attendance_percent, teacher_comment=teacher_comment, generated_date=generated_date,
    )
    buffer = io.BytesIO()
    HTML(string=html_content).write_pdf(buffer)
    return buffer.getvalue()
