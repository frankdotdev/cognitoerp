def upgrade() -> None:
    sql = _SCHEMA_SQL_PATH.read_text()
    # Execute statement-by-statement rather than as one blob — some drivers/
    # pooling setups don't handle multi-statement strings reliably, and
    # per-statement execution gives a much clearer error location if any
    # single CREATE TABLE fails during the first real run against Postgres.
    for statement in sql.split(";"):
        statement = statement.strip()
        if statement:
            op.execute(statement)


